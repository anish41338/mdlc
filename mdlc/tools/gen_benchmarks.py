"""Regenerate docs/BENCHMARKS.md from benchmark artifacts.

Usage:
    python -m mdlc.tools.gen_benchmarks [artifacts/gpu_run_XXX/bench.json ...]

With no argument, uses the newest ``artifacts/gpu_run_*/bench.json``. Every
number in the generated doc is read from the artifact — the doc is a *view*
of measurements, never a place numbers are typed. Wins and losses are both
rendered; each loss gets a gap row so the analysis section has its anchors.
"""

from __future__ import annotations

import argparse
import glob
import json
import os


def _fmt_ms(row: dict) -> str:
    if "median_ms" not in row:
        return f"— ({row.get('error', 'n/a')})"
    return (f"{row['median_ms']:.3f} "
            f"[{row['p10_ms']:.3f}–{row['p90_ms']:.3f}]")


def _fmt_mem(row: dict) -> str:
    b = row.get("device_bytes")
    return f"{b / 1e6:.1f}" if b else "—"


def _fmt_launch(row: dict) -> str:
    l = row.get("launches")
    return str(l) if l is not None else "—"


def generate(paths: list[str], out: str = "docs/BENCHMARKS.md") -> str:
    arts = []
    for p in paths:
        with open(p, encoding="utf-8") as f:
            arts.append((p, json.load(f)))

    lines = ["# Benchmarks", ""]
    lines.append("*Generated by `python -m mdlc.tools.gen_benchmarks` from the "
                 "artifact JSON listed below — no hand-typed numbers. "
                 "Latency: median ms over the configured iterations "
                 "(p10–p90 in brackets), H2D/D2H excluded, fixed seeded "
                 "inputs. Baselines run with their best settings "
                 "(cudnn.benchmark, ORT graph-opt ALL). mdlc kernels are "
                 "IEEE-math (fast-math off).*")
    lines.append("")

    for path, art in arts:
        env = art.get("env", {})
        cfg = art.get("config", {})
        lines.append(f"## {os.path.dirname(path) or path}")
        lines.append("")
        lines.append(f"- GPU: **{env.get('gpu', '?')}** ({env.get('sm_arch', '?')}), "
                     f"driver {env.get('driver', '?')}, CUDA {env.get('cuda_runtime', '?')}")
        lines.append(f"- torch {env.get('torch', '?')}, onnxruntime "
                     f"{env.get('onnxruntime', '?')}, python {env.get('python', '?')}")
        lines.append(f"- git `{env.get('git_sha', '?')[:12]}`, "
                     f"{env.get('timestamp_utc', '?')}")
        lines.append(f"- {cfg.get('iters', '?')} iters / {cfg.get('warmup', '?')} "
                     f"warmups, seed {cfg.get('seed', '?')}. Timing method per "
                     "row: mdlc & torch = CUDA events; ort-cuda = wall clock "
                     "around io_binding run (internally synchronized).")
        lines.append("")
        lines.append("| model | batch | system | latency ms (median [p10–p90]) "
                     "| launches | device MB |")
        lines.append("|---|---|---|---|---|---|")
        by_key: dict[tuple, dict[str, dict]] = {}
        for row in art.get("rows", []):
            by_key.setdefault((row["model"], row["batch"]), {})[row["system"]] = row
            lines.append(
                f"| {row['model']} | {row['batch']} | {row['system']} "
                f"| {_fmt_ms(row)} | {_fmt_launch(row)} | {_fmt_mem(row)} |")
        lines.append("")

        # win/loss summary — losses stated as prominently as wins
        lines.append("### Result summary (computed)")
        lines.append("")
        for (model, batch), systems in sorted(by_key.items()):
            us = systems.get("mdlc", {})
            if "median_ms" not in us:
                lines.append(f"- {model} b{batch}: mdlc row missing/errored — "
                             f"{us.get('error', 'n/a')}")
                continue
            for other in ("torch-eager", "torch-compile", "ort-cuda"):
                o = systems.get(other, {})
                if "median_ms" not in o:
                    continue
                ratio = o["median_ms"] / us["median_ms"]
                if ratio >= 1.0:
                    lines.append(f"- {model} b{batch}: mdlc is "
                                 f"**{ratio:.2f}× faster** than {other} "
                                 f"({us['median_ms']:.3f} vs {o['median_ms']:.3f} ms)")
                else:
                    lines.append(f"- {model} b{batch}: mdlc is "
                                 f"**{1/ratio:.2f}× slower** than {other} "
                                 f"({us['median_ms']:.3f} vs {o['median_ms']:.3f} ms)"
                                 " — see gap analysis")
            if us.get("parity_max_abs_vs_ort") is not None:
                lines.append(f"  - on-device parity vs ORT golden: max_abs "
                             f"{us['parity_max_abs_vs_ort']:.2e}; host fallbacks: "
                             f"{us.get('fallbacks') or 'none'}")
            elif us.get("parity_error"):
                # Say so loudly: a timing whose correctness was never checked
                # must not read as a verified result.
                lines.append(f"  - ⚠ **latency NOT parity-checked** — the ORT "
                             f"golden was unavailable ({us['parity_error']}); "
                             f"host fallbacks: {us.get('fallbacks') or 'none'}")
        lines.append("")

    lines.append("## Gap analysis")
    lines.append("")
    lines.append("Where mdlc loses (typically to ORT CUDA EP on conv-heavy "
                 "graphs), the cause is algorithmic, not mysterious: ORT "
                 "dispatches cuDNN's shape-specialized implicit-GEMM / "
                 "Winograd conv kernels with tensor-core paths, while mdlc "
                 "lowers conv via explicit im2col + a tiled fp32 SGEMM with "
                 "no tensor cores and no double buffering. The wins at "
                 "batch-1 come from the launch-bound regime: fused kernels "
                 "cut launch count (per-row launch column) and remove "
                 "framework dispatch. Closing the conv gap means implicit "
                 "GEMM (gather patches inside the GEMM K-loop) and a Winograd "
                 "path for 3×3 s1 — both scoped in docs/STATUS.md as the "
                 "post-lock stretch.")
    lines.append("")
    lines.append("*Source artifacts:* " + ", ".join(f"`{p}`" for p, _ in arts))
    lines.append("")

    os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
    # Explicit UTF-8: the default encoding is cp1252 on Windows, which cannot
    # represent characters this report legitimately uses.
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"wrote {out} from {len(arts)} artifact(s)")
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("artifacts", nargs="*",
                    help="bench.json paths (default: newest artifacts/gpu_run_*)")
    ap.add_argument("--out", default="docs/BENCHMARKS.md")
    args = ap.parse_args(argv)
    paths = args.artifacts
    if not paths:
        cands = sorted(glob.glob("artifacts/gpu_run_*/bench.json"))
        if not cands:
            raise SystemExit("no artifacts/gpu_run_*/bench.json found — run the "
                             "suite on a GPU first (artifacts/GPU_TODO.md)")
        paths = [cands[-1]]
    generate(paths, out=args.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
